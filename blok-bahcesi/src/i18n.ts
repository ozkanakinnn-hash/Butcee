let lang: Lang = 'tr';
export function setLang(l: Lang) { lang = l; document.documentElement.lang = l; }
export function getLang(): Lang { return lang; }

export function t(key: Key | string, vars?: Record<string, string | number>): string {
  const dict = (lang === 'en' ? EN : TR) as Record<string, string>;
  let s = dict[key] ?? (TR as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
