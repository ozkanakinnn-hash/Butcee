private val prayerWords = listOf("İmsak", "Güneş", "Öğle", "İkindi", "Akşam", "Yatsı")

/** Türkçe metni seçili dile çevirir (sözlük + birkaç dinamik kalıp). */
fun t(tr: String): String {
  if (!AppLanguage.isEnglish) return tr
  dictionary[tr]?.let { return it }
  // "Öğle Vaktine Kalan" -> "Time until Dhuhr"
  Regex("^(.+) Vaktine Kalan$").find(tr)?.let { return "Time until " + t(it.groupValues[1]) }
  // "Yatsı 19:33" -> "Isha 19:33"
  for (w in prayerWords) if (tr.startsWith("$w ")) return t(w) + tr.removePrefix(w)
  return tr
}
